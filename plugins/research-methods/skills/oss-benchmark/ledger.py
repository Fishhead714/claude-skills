#!/usr/bin/env python3
"""ledger — the "already evaluated" ledger for oss-benchmark.

It exists for one reason: never evaluate the same candidate twice. Once a candidate has been
measured and refuted, the verdict is usually stable; re-checking it is pure waste.

The source of truth is ledger.jsonl (one JSON object per line). LEDGER.md is re-rendered from it
after every write and is only a human-readable view. **Don't edit LEDGER.md by hand** — the next
write overwrites it. (Why not use a Markdown table as the source of truth: `|` and newlines inside
cell text silently break table parsing and lose data.)

Location: $OSS_BENCHMARK_DIR if set, else --dir, else ./oss-benchmark in the current directory.

Usage:
    ledger.py check "reranker"                 # step one: has this direction/candidate been evaluated?
    ledger.py list [--verdict rejected] [--target my-search-tool]
    ledger.py add --repo owner/name --topic "OCR upgrade" --target my-search-tool \\
        --verdict rejected --reason "..." [--evidence "file:line or command + error"] [--report path]
    ledger.py render                            # only regenerate LEDGER.md

Standard library only.
"""

import argparse
import json
import os
import sys
from datetime import date
from pathlib import Path

VERDICTS = ("adopted", "rejected", "pending")
VERDICT_LABEL = {
    "adopted": "✅ adopted",
    "rejected": "⛔ refuted / rejected",
    "pending": "🕓 pending",
}


def base_dir(cli_dir=None):
    env = os.environ.get("OSS_BENCHMARK_DIR")
    if env:
        return Path(env)
    if cli_dir:
        return Path(cli_dir)
    return Path.cwd() / "oss-benchmark"


def paths(cli_dir=None):
    b = base_dir(cli_dir)
    return b, b / "ledger.jsonl", b / "LEDGER.md"


def load(jsonl):
    """Return (rows, bad_lines). If bad_lines is non-empty, writing back is refused: save() can
    only write the rows that parsed, so writing would silently erase the bad lines and the
    verdicts they record."""
    rows, bad = [], []
    if not jsonl.is_file():
        return rows, bad
    for i, line in enumerate(jsonl.read_text(encoding="utf-8").splitlines(), 1):
        line = line.strip()
        if not line:
            continue
        try:
            rows.append(json.loads(line))
        except json.JSONDecodeError as e:
            bad.append(i)
            print(f"warning: {jsonl}:{i} is not valid JSON, skipped ({e})", file=sys.stderr)
    return rows, bad


def save(jsonl, rows):
    jsonl.parent.mkdir(parents=True, exist_ok=True)
    tmp = jsonl.with_suffix(".jsonl.tmp")
    tmp.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows), encoding="utf-8")
    tmp.replace(jsonl)  # atomic replace: a crash mid-write never leaves half a ledger


def cell(s):
    """Put arbitrary text into a Markdown table cell without breaking the table."""
    if s is None:
        return ""
    return str(s).replace("\\", "\\\\").replace("|", "\\|").replace("\n", "<br>").strip()


def render_md(rows, md):
    rows = sorted(rows, key=lambda r: (r.get("date", ""), r.get("repo", "")), reverse=True)
    out = [
        "# Open-source candidate evaluation ledger",
        "",
        "> Generated by `ledger.py` (oss-benchmark skill). **Do not edit this file** — the source of truth is `ledger.jsonl` in the same directory.",
        "> Check here before a new round, so refuted candidates are not evaluated again.",
        "",
    ]
    for v in VERDICTS:
        sub = [r for r in rows if r.get("verdict") == v]
        out.append(f"## {VERDICT_LABEL[v]} ({len(sub)})")
        out.append("")
        if not sub:
            out.append("_none_")
            out.append("")
            continue
        out.append("| Date | Candidate | Topic | Target | Reason | Evidence | Report |")
        out.append("|---|---|---|---|---|---|---|")
        for r in sub:
            repo = r.get("repo", "")
            link = f"[{cell(repo)}](https://github.com/{repo})" if "/" in repo else cell(repo)
            out.append("| {} | {} | {} | {} | {} | {} | {} |".format(
                cell(r.get("date")), link, cell(r.get("topic")), cell(r.get("target")),
                cell(r.get("reason")), cell(r.get("evidence")), cell(r.get("report"))))
        out.append("")
    md.parent.mkdir(parents=True, exist_ok=True)
    md.write_text("\n".join(out), encoding="utf-8")


def match(row, q):
    q = q.lower()
    return any(q in str(row.get(k, "")).lower() for k in ("repo", "topic", "target", "reason"))


def show(rows):
    for r in rows:
        print(f"[{VERDICT_LABEL.get(r.get('verdict'), r.get('verdict'))}] {r.get('repo')}"
              f"  ({r.get('date')}, target {r.get('target')}, topic {r.get('topic')})")
        if r.get("reason"):
            print(f"    reason:   {r['reason']}")
        if r.get("evidence"):
            print(f"    evidence: {r['evidence']}")
        if r.get("report"):
            print(f"    report:   {r['report']}")


def main():
    ap = argparse.ArgumentParser(description="oss-benchmark ledger of evaluated projects")
    ap.add_argument("--dir", help="ledger directory (ignored if $OSS_BENCHMARK_DIR is set)")
    sub = ap.add_subparsers(dest="cmd", required=True)

    c = sub.add_parser("check", help="has this candidate/direction been evaluated?")
    c.add_argument("query")

    l = sub.add_parser("list", help="list the ledger")
    l.add_argument("--verdict", choices=VERDICTS)
    l.add_argument("--target")

    a = sub.add_parser("add", help="record a verdict (refutations too!)")
    a.add_argument("--repo", required=True, help="owner/name")
    a.add_argument("--topic", required=True, help="topic of this round, e.g. 'OCR upgrade'")
    a.add_argument("--target", required=True, help="your own project being benchmarked")
    a.add_argument("--verdict", required=True, choices=VERDICTS)
    a.add_argument("--reason", required=True, help="specific enough to reproduce; not just 'incompatible'")
    a.add_argument("--evidence", default="", help="file:line, command + error, or measured numbers")
    a.add_argument("--report", default="", help="path of this round's report")
    a.add_argument("--date", default=None, help="default: today")
    a.add_argument("--update", action="store_true", help="overwrite an existing repo+target entry")

    sub.add_parser("render", help="regenerate LEDGER.md from ledger.jsonl")

    args = ap.parse_args()
    _, jsonl, md = paths(args.dir)
    rows, bad = load(jsonl)

    if args.cmd == "check":
        hits = [r for r in rows if match(r, args.query)]
        if not hits:
            print(f"No ledger entry for '{args.query}' ({len(rows)} entries) — new direction, go ahead.")
            return 0
        print(f"⚠️  {len(hits)} related ledger entr{'y' if len(hits) == 1 else 'ies'}; read the verdicts before re-evaluating:\n")
        show(hits)
        return 0

    if args.cmd == "list":
        sel = rows
        if args.verdict:
            sel = [r for r in sel if r.get("verdict") == args.verdict]
        if args.target:
            sel = [r for r in sel if args.target.lower() in str(r.get("target", "")).lower()]
        sel.sort(key=lambda r: r.get("date", ""), reverse=True)
        if not sel:
            print("(empty)")
        else:
            show(sel)
        return 0

    if args.cmd == "render":
        render_md(rows, md)
        print(f"Regenerated {md} ({len(rows)} entries)")
        return 0

    # add
    if bad:
        print(f"Refusing to write: {jsonl} line(s) {', '.join(map(str, bad))} are not valid JSON. "
              "Writing now would drop those lines and the verdicts they record; fix them first.", file=sys.stderr)
        return 2
    if len(args.reason) < 10:
        print("Refusing to write: --reason is too short. Make it reproducible, e.g. "
              "'fails to build: needs CUDA_HOME, not set here' rather than 'incompatible'.", file=sys.stderr)
        return 2
    dup = [r for r in rows if r.get("repo") == args.repo and r.get("target") == args.target]
    if dup and not args.update:
        print(f"Refusing to write: {args.repo} against {args.target} already has an entry. "
              "Use --update to overwrite, or read the old verdict first:\n", file=sys.stderr)
        show(dup)
        return 2
    entry = {
        "date": args.date or date.today().isoformat(),
        "repo": args.repo,
        "topic": args.topic,
        "target": args.target,
        "verdict": args.verdict,
        "reason": args.reason,
        "evidence": args.evidence,
        "report": args.report,
    }
    if dup:
        first = min((r.get("date", "") for r in dup), default="")
        entry["first_evaluated"] = dup[0].get("first_evaluated") or first
        rows = [r for r in rows if not (r.get("repo") == args.repo and r.get("target") == args.target)]
    rows.append(entry)
    save(jsonl, rows)
    render_md(rows, md)
    print(f"Recorded: [{VERDICT_LABEL[args.verdict]}] {args.repo} → {args.target}")
    print(f"  {jsonl}")
    print(f"  {md}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
